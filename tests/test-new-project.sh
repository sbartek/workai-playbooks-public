#!/usr/bin/env bash
# Tests for the workai-new-project scripts against a throwaway workai root.
set -u
here="$(cd "$(dirname "$0")/.." && pwd)"
skill="$here/skills/workai-new-project"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
export WORKAI_ROOT="$tmp/workai"
# Pretend git's default branch is master, so the scripts must ask for main.
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=init.defaultBranch GIT_CONFIG_VALUE_0=master
fails=0
ok() { echo "ok   $1"; }
bad() { echo "FAIL $1"; [ -f "$tmp/out" ] && sed 's/^/     /' "$tmp/out"; fails=$((fails + 1)); }

mkdir -p "$WORKAI_ROOT/projects/01-first" "$WORKAI_ROOT/archives/03-old" "$WORKAI_ROOT/projects/ceramics"
printf '# Projects\n\n## 01 — First\n\n## L38 — Ceramics\nold\n' >"$WORKAI_ROOT/CLAUDE.md"
: >"$WORKAI_ROOT/.gitignore"

bash "$skill/new-project.sh" home-gym "Home Gym & Co/2" >"$tmp/out" 2>&1 && ok "creates a hub" || bad "creates a hub"
hub="$WORKAI_ROOT/projects/04-home-gym"
[ -d "$hub" ] && ok "next number counts archives (04)" || bad "next number counts archives (04)"

for f in README.md CLAUDE.md STRUCTURE .gitignore backlog/TEMPLATE.md backlog/README.md; do
  [ -f "$hub/$f" ] && ok "has $f" || bad "has $f"
done
for d in backlog/todo backlog/doing backlog/done backlog/archive notes repos worktrees; do
  [ -d "$hub/$d" ] && ok "has $d/" || bad "has $d/"
done
[ "$(cat "$hub/STRUCTURE")" = "$(cat "$here/VERSION")" ] && ok "STRUCTURE = current VERSION" || bad "STRUCTURE = current VERSION"
grep -q '^# 04 — Home Gym & Co/2$' "$hub/README.md" && ok "title filled in, special characters kept" || bad "title filled in, special characters kept"
[ -z "$(git -C "$hub" status --porcelain)" ] && [ "$(git -C "$hub" rev-list --count HEAD)" = 1 ] && ok "hub is a committed git repo" || bad "hub is a committed git repo"
[ "$(git -C "$hub" branch --show-current)" = main ] && ok "hub branch is main" || bad "hub branch is main"
git -C "$hub" check-ignore -q repos/x && git -C "$hub" check-ignore -q worktrees/x && ok "hub ignores repos/ and worktrees/" || bad "hub ignores repos/ and worktrees/"
grep -qx 'projects/04-home-gym/' "$WORKAI_ROOT/.gitignore" && ok "added to workai .gitignore" || bad "added to workai .gitignore"
# The index is generated by report.py --index (card 01-151), never a hand section.
head -1 "$WORKAI_ROOT/CLAUDE.md" | grep -qx '# Workai index' && grep -q 'do not edit by' "$WORKAI_ROOT/CLAUDE.md" \
  && ok "CLAUDE.md regenerated by report.py --index" || bad "CLAUDE.md regenerated by report.py --index"
grep -q '^- \*\*04 Home Gym & Co/2\*\*.*`projects/04-home-gym/`' "$WORKAI_ROOT/CLAUDE.md" \
  && ok "index lists the new hub" || bad "index lists the new hub"
! grep -q '^## [0-9L][0-9]' "$WORKAI_ROOT/CLAUDE.md" && ok "no hand-written ## NN or ## Lnn section" || bad "no hand-written ## NN or ## Lnn section"
python3 "$here/skills/workai-open-project/report.py" --index "$WORKAI_ROOT" | cmp -s - "$WORKAI_ROOT/CLAUDE.md" \
  && ok "CLAUDE.md is exactly the generated index" || bad "CLAUDE.md is exactly the generated index"
[ ! -e "$WORKAI_ROOT/.workai.lock" ] && ok "lock released after regenerating" || bad "lock released after regenerating"

# Same top-level layout as the real 01 hub.
real="$HOME/workai/projects/01-workai-playbooks"
if [ -d "$real" ]; then
  want="$(cd "$real" && ls -A | grep -v '^\.git$' | sort | tr '\n' ' ')"
  got="$(cd "$hub" && ls -A | grep -v '^\.git$' | sort | tr '\n' ' ')"
  [ "$want" = "$got" ] && ok "same top-level layout as 01-workai-playbooks" || { echo "     want: $want"; echo "     got:  $got"; bad "same top-level layout as 01-workai-playbooks"; }
fi

bash "$skill/new-project.sh" home-gym "Again" >"$tmp/out" 2>&1 && bad "refuses a duplicate name" || ok "refuses a duplicate name"
bash "$skill/new-project.sh" Bad_Name "X" >"$tmp/out" 2>&1 && bad "refuses a bad name" || ok "refuses a bad name"

bash "$skill/add-repo.sh" "$hub" app >"$tmp/out" 2>&1 && ok "adds a repo" || bad "adds a repo"
[ -d "$hub/repos/app/.git" ] && [ -d "$hub/worktrees/app" ] && ok "repo and its worktrees/ folder exist" || bad "repo and its worktrees/ folder exist"
[ "$(git -C "$hub/repos/app" branch --show-current)" = main ] && ok "new repo branch is main" || bad "new repo branch is main"
grep -q 'worktree_dir: ../../worktrees/{project}' "$hub/repos/app/.workmux.yaml" && ok "local .workmux.yaml written" || bad "local .workmux.yaml written"
[ -z "$(git -C "$hub/repos/app" status --porcelain)" ] && ok ".workmux.yaml excluded from the repo" || bad ".workmux.yaml excluded from the repo"
[ -x "$hub/repos/app/.git/hooks/pre-push" ] && grep -q '# workai pre-push scan' "$hub/repos/app/.git/hooks/pre-push" && [ -f "$hub/repos/app/.git/hooks/workai-scan.py" ] && ok "add-repo installs the pre-push scan" || bad "add-repo installs the pre-push scan"
bash "$skill/add-repo.sh" "$WORKAI_ROOT/projects/ceramics" x >"$tmp/out" 2>&1 && bad "refuses a non-hub" || ok "refuses a non-hub"

# a cloned repo that tracks its own .workmux.yaml keeps it
src="$tmp/src-wm"; mkdir -p "$src" && git -C "$src" init -q && printf 'worktree_dir: custom\n' >"$src/.workmux.yaml" \
  && git -C "$src" add -A && git -c user.name=t -c user.email=t@t -C "$src" commit -qm wm
bash "$skill/add-repo.sh" "$hub" wm "$src" >"$tmp/out" 2>&1 && [ "$(cat "$hub/repos/wm/.workmux.yaml")" = "worktree_dir: custom" ] \
  && [ -z "$(git -C "$hub/repos/wm" status --porcelain)" ] && ok "clone keeps its tracked .workmux.yaml" || bad "clone keeps its tracked .workmux.yaml"


# Titles (card 01-115): one-pass substitution, validated before anything is made.
bash "$skill/new-project.sh" dated "NN DATE TITLE plan" >"$tmp/out" 2>&1 || bad "creates a hub with placeholder words in the title"
d="$(ls -d "$WORKAI_ROOT"/projects/[0-9][0-9]-dated 2>/dev/null)"
num="$(basename "$d" | cut -c1-2)"
grep -qx "# $num — NN DATE TITLE plan" "$d/README.md" && grep -qx "# $num — NN DATE TITLE plan (hub)" "$d/CLAUDE.md" \
  && ok "placeholders inside the title stay as typed" || bad "placeholders inside the title stay as typed"
count() { ls -d "$WORKAI_ROOT"/projects/[0-9][0-9]-* | wc -l | tr -d ' '; }
n0="$(count)"
for t in "$(printf 'two\nlines')" "" "  padded" "# heading" "$(printf 'tab\there')" "$(printf '%081d' 0)"; do
  bash "$skill/new-project.sh" badtitle "$t" >"$tmp/out" 2>&1 && bad "refuses title $(printf %q "$t")" || true
done
[ "$(count)" = "$n0" ] && ! compgen -G "$WORKAI_ROOT/projects/*-badtitle" >/dev/null && ok "bad titles refused, nothing made" || bad "bad titles refused, nothing made"
grep -q "badtitle" "$WORKAI_ROOT/CLAUDE.md" "$WORKAI_ROOT/.gitignore" && bad "bad title left no index entry" || ok "bad title left no index entry"
mkdir -p "$tmp/fakebin"
printf '#!/bin/sh\ncase "$*" in *commit*) echo "fatal: cannot commit" >&2; exit 128;; esac\nexec %s "$@"\n' "$(command -v git)" >"$tmp/fakebin/git"
chmod +x "$tmp/fakebin/git"
PATH="$tmp/fakebin:$PATH" bash "$skill/new-project.sh" halfmade "Half made" >"$tmp/out" 2>&1 && bad "a failing commit fails" || true
[ -z "$(ls -d "$WORKAI_ROOT"/projects/*-halfmade 2>/dev/null)" ] && grep -q "removed the half-made" "$tmp/out" \
  && ! grep -q halfmade "$WORKAI_ROOT/CLAUDE.md" && ok "a failure mid-way leaves no half-made hub" || bad "a failure mid-way leaves no half-made hub"

# Registering under the lock and committing in a git workai root (card 01-151).
gw() { git -c user.name=t -c user.email=t@t "$@"; }
gw -C "$WORKAI_ROOT" init -q -b main && gw -C "$WORKAI_ROOT" add CLAUDE.md .gitignore && gw -C "$WORKAI_ROOT" commit -qm base
echo "someone else's work" >"$WORKAI_ROOT/next.md"
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t
bash "$skill/new-project.sh" committed "Committed" >"$tmp/out" 2>&1 && ok "creates a hub in a git workai root" || bad "creates a hub in a git workai root"
c="$(ls -d "$WORKAI_ROOT"/projects/[0-9][0-9]-committed | xargs basename)"
[ -z "$(gw -C "$WORKAI_ROOT" status --porcelain -- CLAUDE.md .gitignore)" ] && gw -C "$WORKAI_ROOT" show --stat HEAD | grep -q 'CLAUDE.md' \
  && gw -C "$WORKAI_ROOT" show HEAD:CLAUDE.md | grep -q "\`projects/$c/\`" && ok "index and .gitignore committed" || bad "index and .gitignore committed"
[ "$(gw -C "$WORKAI_ROOT" show --name-only --format= HEAD | sort | tr '\n' ' ')" = ".gitignore CLAUDE.md " ] && gw -C "$WORKAI_ROOT" status --porcelain | grep -q 'next.md' \
  && ok "commit holds only CLAUDE.md and .gitignore" || bad "commit holds only CLAUDE.md and .gitignore"
mkdir "$WORKAI_ROOT/.workai.lock" && printf 'since=%s\npid=%s\nhost=%s\nsession=other\nowner=other agent\n' "$(date +%s)" "$$" "$(hostname -s 2>/dev/null || hostname)" >"$WORKAI_ROOT/.workai.lock/owner"
before="$(cat "$WORKAI_ROOT/CLAUDE.md")"
CLAUDE_CODE_SESSION_ID=mine WORKAI_LOCK_TIMEOUT=0 bash "$skill/new-project.sh" blocked "Blocked" >"$tmp/out" 2>&1 \
  && bad "a lock held by another agent stops the index" || ok "a lock held by another agent stops the index"
[ "$(cat "$WORKAI_ROOT/CLAUDE.md")" = "$before" ] && grep -q 'not regenerated' "$tmp/out" && [ -d "$WORKAI_ROOT/.workai.lock" ] \
  && ok "index untouched and the other lock kept" || bad "index untouched and the other lock kept"
CLAUDE_CODE_SESSION_ID=other bash "$here/skills/workai-open-project/regen-index.sh" >"$tmp/out" 2>&1 && grep -q blocked "$WORKAI_ROOT/CLAUDE.md" \
  && [ -d "$WORKAI_ROOT/.workai.lock" ] && ok "regenerates under its own session's lock, leaves it held" || bad "regenerates under its own session's lock, leaves it held"
WORKAI_LOCK_OWNER="other agent" bash "$here/skills/workai-open-project/regen-index.sh" >"$tmp/out" 2>&1 && ok "WORKAI_LOCK_OWNER names the holder" || bad "WORKAI_LOCK_OWNER names the holder"
WORKAI_LOCK_OWNER="me" bash "$here/skills/workai-open-project/regen-index.sh" >"$tmp/out" 2>&1 && bad "WORKAI_LOCK_OWNER that does not hold it is refused" || ok "WORKAI_LOCK_OWNER that does not hold it is refused"
rm -r "$WORKAI_ROOT/.workai.lock"

[ "$fails" -eq 0 ] && echo "all tests pass" || { echo "$fails test(s) failed"; exit 1; }
